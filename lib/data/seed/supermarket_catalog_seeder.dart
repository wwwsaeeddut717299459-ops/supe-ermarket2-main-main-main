  static Future<void> seed(AppDatabase db) async {
    final existing = await db.categoriesDao.getAll();
    if (existing.isNotEmpty) return;
    await db.transaction(() async {
      var sequence = 1;
      for (final entry in catalog.entries) {
        final categoryId = await db.categoriesDao.insertCategory(
          CategoriesCompanion.insert(name: entry.key),
        );
        for (final name in entry.value) {
          await db.productsDao.insertProduct(
            ProductsCompanion.insert(
              barcode: _barcode(sequence++),
              name: name,
              categoryId: Value(categoryId),
            ),
          );
        }
      }
    });
  }

  static String _barcode(int sequence) {
    final body = '290${sequence.toString().padLeft(9, '0')}';
    var sum = 0;
    for (var i = 0; i < body.length; i++) {
      final digit = int.parse(body[i]);
      sum += i.isEven ? digit : digit * 3;
    }
    final check = (10 - (sum % 10)) % 10;
    return '$body$check';
  }
